import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'

assert.ok(process.env.STAFF_PASSCODE, 'Supply the local staff passcode through STAFF_PASSCODE')
const browser = await chromium.launch({ channel: 'msedge', headless: true })
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  const page = await context.newPage()
  const admin = await context.newPage()
  async function checkTheme(page, theme, accent = theme === 'light' ? '#512bd4' : '#c4b5fd') {
    assert.equal(await page.locator('html').getAttribute('data-theme'), theme)
    assert.equal(await page.locator('html').evaluate(element => getComputedStyle(element).colorScheme), theme)
    assert.equal(await page.locator('html').evaluate(element => getComputedStyle(element).getPropertyValue('--accent').trim()),
      accent, 'Both palettes must use the .NET purple family')
  }
  async function checkContrast(page, selector, ownBackground = false) {
    const ratio = await page.locator(selector).first().evaluate((element, ownBackground) => {
      const rgb = value => value.trim().startsWith('#')
        ? value.trim().slice(1).match(/.{2}/g).map(channel => parseInt(channel, 16))
        : value.match(/[\d.]+/g).slice(0, 3).map(Number)
      const luminance = color => rgb(color).map(channel => {
        const c = channel / 255
        return c <= .04045 ? c / 12.92 : ((c + .055) / 1.055) ** 2.4
      }).reduce((sum, channel, index) => sum + channel * [.2126, .7152, .0722][index], 0)
      const style = getComputedStyle(element)
      const ink = luminance(style.color)
      const background = luminance(ownBackground ? style.backgroundColor
        : getComputedStyle(document.documentElement).getPropertyValue('--surface'))
      return (Math.max(ink, background) + .05) / (Math.min(ink, background) + .05)
    }, ownBackground)
    assert.ok(ratio >= 4.5, `${selector} text contrast ${ratio.toFixed(2)} must be at least 4.5:1`)
  }
  await page.goto('http://127.0.0.1:5173')
  await page.getByRole('heading', { name: /the room is/i }).waitFor()
  const wallStyle = page.getByRole('combobox', { name: 'Wall style' })
  assert.equal(await wallStyle.inputValue(), 'communityevent', 'Community Event must be the default wall style')
  await checkTheme(page, 'dark', '#b9aaee')
  await checkContrast(page, '.post-text')
  await checkContrast(page, '.brand strong')
  const toggle = page.getByRole('button', { name: 'Light theme' })
  await toggle.focus()
  await page.keyboard.press('Enter')
  await checkTheme(page, 'light', '#5728dc')
  await checkContrast(page, '.post-text')
  await checkContrast(page, '.post-author')
  await checkContrast(page, '.brand strong')
  await page.reload()
  await page.getByRole('heading', { name: /the room is/i }).waitFor()
  assert.equal(await wallStyle.inputValue(), 'communityevent')
  await checkTheme(page, 'light', '#5728dc')
  await page.getByRole('button', { name: /expand post by/i }).first().click()
  await checkContrast(page, '.post-modal blockquote')
  await page.getByRole('button', { name: 'Close expanded post' }).click()
  await wallStyle.selectOption('classic')
  await page.reload()
  await page.getByRole('heading', { name: /the room is/i }).waitFor()
  assert.equal(await wallStyle.inputValue(), 'classic', 'A saved wall style must take precedence over the default')
  await checkTheme(page, 'light')
  await checkContrast(page, '.brand-mark', true)
  await page.getByRole('button', { name: 'Light theme' }).click()
  await checkTheme(page, 'dark')
  await checkContrast(page, '.brand-mark', true)
  await page.getByRole('button', { name: 'Light theme' }).click()
  await checkTheme(page, 'light')
  assert.equal(await page.getByRole('link', { name: 'Submit a question', exact: true }).getAttribute('href'), `${(process.env.SUBMISSION_BASE_URL ?? 'http://127.0.0.1:5082').replace(/\/$/, '')}/`)
  await page.goto(process.env.SUBMISSION_BASE_URL ?? 'http://127.0.0.1:5082')
  await page.getByLabel('Your question', { exact: true }).waitFor()
  await checkTheme(page, 'dark')
  await page.getByRole('button', { name: 'Light theme' }).click()
  await checkTheme(page, 'light')
  await checkContrast(page, '.question-card label')
  await checkContrast(page, '.question-send', true)

  await admin.goto('http://127.0.0.1:5174')
  await admin.getByLabel('Access code').waitFor()
  await checkTheme(admin, 'dark')
  await admin.getByRole('button', { name: 'Light theme' }).click()
  await checkContrast(admin, '.staff-login label')
  await checkContrast(admin, '.button-primary', true)
  await admin.getByLabel('Access code').fill(process.env.STAFF_PASSCODE)
  await admin.getByRole('button', { name: /open staff console/i }).click()
  await admin.getByRole('heading', { name: /keep the signal/i }).waitFor()
  await checkContrast(admin, '.queue-item-main > p')
  await admin.getByRole('button', { name: 'Grid', exact: true }).click()
  await admin.getByRole('tab', { name: 'Approved', exact: true }).click()
  await admin.locator('.queue-item').first().waitFor()
  await checkContrast(admin, '.queue-item-main > p')
  await admin.getByRole('button', { name: /portal (open|paused)/i }).click()
  await admin.getByRole('dialog').waitFor()
  await checkContrast(admin, '.confirmation-dialog p')
  await admin.getByRole('button', { name: 'Cancel', exact: true }).click()
  await admin.getByRole('tab', { name: /social connections/i }).click()
  await admin.locator('.source-setup-card').first().waitFor()
  await checkContrast(admin, '.source-setup-card p')
  await admin.getByRole('tab', { name: 'Event report' }).click()
  await admin.locator('.metric-card').first().waitFor()
  await checkTheme(admin, 'light')
  await admin.reload()
  await admin.getByRole('heading', { name: /keep the signal/i }).waitFor()
  await checkTheme(admin, 'light')
  for (const width of [390, 340]) {
    for (const site of [page, admin]) {
      await site.setViewportSize({ width, height: 844 })
      assert.ok(await site.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `No mobile overflow at ${width}px on ${site.url()}`)
      assert.ok(await site.getByRole('button', { name: 'Light theme' }).isVisible())
    }
  }
  await page.getByRole('button', { name: 'Light theme' }).click()
  await checkTheme(page, 'dark')
  await checkTheme(admin, 'light')
  await admin.getByRole('button', { name: 'Light theme' }).click()
  await checkTheme(admin, 'dark')
  console.log('Theme proof passed: default Community Event and saved Classic, public/portal/staff login and all staff tabs, persistence, independent origins, keyboard toggle, 4.5:1 text contrast, mobile 390/340px, and return to dark.')
} finally {
  await browser.close()
}
