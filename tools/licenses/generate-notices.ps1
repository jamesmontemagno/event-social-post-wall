<#
.SYNOPSIS
Generates public notices from restored NuGet metadata and installed web dependencies.
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$web = Join-Path $root 'src\EventWall.Web'
$output = Join-Path $web 'public\THIRD-PARTY-NOTICES.txt'
$text = [System.Text.StringBuilder]::new()
$null = $text.AppendLine(@'
Event Social Post Wall - Third-party licenses and notices
=========================================================
Generated by tools\licenses\generate-notices.ps1. Do not edit by hand.

Scope: restored API and local Aspire AppHost NuGet dependencies (including
development tooling), Blazor Server from the ASP.NET Core shared framework,
shipped React dependencies, the self-hosted Space Grotesk font, TypeScript tooling, and
bundled illustrations.
Package copyrights, license declarations and bundled notices are retained below.
The host-provided .NET runtime and its notices are also included.
Application code is MIT licensed; third-party components retain the terms below.
GitHub Copilot is credited for AI-assisted development, not as an open-source
runtime dependency. Product names and links do not imply endorsement.
SQLite itself is public domain: https://www.sqlite.org/copyright.html
SQLitePCLRaw packages have their own licenses, included below.
'@)

function Add-Section([string]$heading, [string]$body) {
    $null = $text.AppendLine("`n================================================================")
    $null = $text.AppendLine($heading)
    $null = $text.AppendLine("================================================================`n")
    $null = $text.AppendLine($body.Trim())
}

Add-Section 'Mod the dotnet-bot: portal question illustrations' @'
Twelve head-and-shoulders PNG portraits exported from the official generator:
https://mod-dotnet-bot.net/
Illustrations by the .NET Foundation community.
The illustrations and generated mods are CC0 1.0 Universal:
https://creativecommons.org/publicdomain/zero/1.0/
Artwork source: https://github.com/dotnet-foundation/mod-dotnet-bot
Generator terms: https://mod-dotnet-bot.net/terms/
The bot is a community mascot, not this application's logo or an endorsement.
'@

$fontDirectory = Join-Path $web 'node_modules\@fontsource-variable\space-grotesk'
$fontPackage = Get-Content (Join-Path $fontDirectory 'package.json') -Raw | ConvertFrom-Json
Add-Section "npm: @fontsource-variable/space-grotesk/$($fontPackage.version) (Space Grotesk font)" "Declared license: $($fontPackage.license)`nSelf-hosted WOFF2 files; no Google Fonts requests are made."
Add-Section 'Space Grotesk: LICENSE' (Get-Content (Join-Path $fontDirectory 'LICENSE') -Raw)

$reactLicense = Get-Content (Join-Path $web 'node_modules\react\LICENSE') -Raw
$mit = $reactLicense.Substring($reactLicense.IndexOf('Permission is hereby granted'))
$apache = Get-Content (Join-Path $web 'node_modules\typescript\LICENSE') -Raw
$templates = @{ 'MIT' = $mit; 'Apache-2.0' = $apache }
$seen = @{}
foreach ($project in @('EventWall.Api', 'EventWall.AppHost')) {
    $assetsPath = Join-Path $root "src\$project\obj\project.assets.json"
    if (-not (Test-Path $assetsPath)) { throw "Restore $project before generating notices." }
    $assets = Get-Content $assetsPath -Raw | ConvertFrom-Json
    foreach ($library in ($assets.libraries.PSObject.Properties | Sort-Object Name)) {
        if ($library.Value.type -ne 'package' -or $seen.ContainsKey($library.Name)) { continue }
        $seen[$library.Name] = $true
        $directory = $null
        foreach ($folder in $assets.packageFolders.PSObject.Properties.Name) {
            $candidate = Join-Path $folder $library.Value.path
            if (Test-Path $candidate) { $directory = $candidate; break }
        }
        if (-not $directory) { throw "Restored package missing: $($library.Name)" }
        [xml]$nuspec = Get-Content (Get-ChildItem $directory -Filter '*.nuspec' | Select-Object -First 1).FullName
        $metadata = $nuspec.package.metadata
        $license = [string]$metadata.license.InnerText
        if (-not $license) { throw "No license declared for $($library.Name); review it manually." }
        Add-Section "$project dependency: $($library.Name)" @"
Authors: $($metadata.authors)
$($metadata.copyright)
Project: $($metadata.projectUrl)
Declared license: $license
"@
        $licenseFiles = @(Get-ChildItem $directory -File | Where-Object { $_.Name -match '^(LICENSE|LICENCE|COPYING)(\.txt|\.md)?$' })
        if ($metadata.license.type -eq 'file') {
            $declaredFile = Join-Path $directory $license
            if (-not (Test-Path $declaredFile)) { throw "License file missing for $($library.Name): $license" }
            $licenseFiles = @(Get-Item $declaredFile)
        }
        if ($licenseFiles.Count -gt 0) {
            foreach ($file in $licenseFiles) { Add-Section "$($library.Name): $($file.Name)" (Get-Content $file.FullName -Raw) }
        }
        else {
            if (-not $templates.ContainsKey($license)) {
                if ($library.Name -like 'Google.Protobuf/*' -and $license -eq 'BSD-3-Clause') {
                    $templates[$license] = (Invoke-WebRequest 'https://raw.githubusercontent.com/protocolbuffers/protobuf/main/LICENSE').Content
                }
                else { throw "No full license text for $($library.Name) ($license); add a reviewed source." }
            }
            Add-Section "$($library.Name): $license terms" $templates[$license]
        }
        foreach ($notice in (Get-ChildItem $directory -File | Where-Object { $_.Name -match '(?i)(third.?party.*notice|^notice(\.txt|\.md)?$)' })) {
            Add-Section "$($library.Name): $($notice.Name)" (Get-Content $notice.FullName -Raw)
        }
    }
}

foreach ($name in @('react', 'react-dom', 'scheduler', 'typescript', 'qrcode.react')) {
    $directory = Join-Path $web "node_modules\$name"
    $package = Get-Content (Join-Path $directory 'package.json') -Raw | ConvertFrom-Json
    Add-Section "npm: $name/$($package.version)" "Declared license: $($package.license)"
    $files = @(Get-ChildItem $directory -File | Where-Object { $_.Name -match '(?i)^(license(\.txt|\.md)?|notice(\.txt|\.md)?|third.*notice.*)$' })
    if ($files.Count -eq 0) { throw "Missing license for $name" }
    foreach ($file in $files) { Add-Section "${name}: $($file.Name)" (Get-Content $file.FullName -Raw) }
}
Add-Section 'qrcode.react bundled QR Code generator: Project Nayuki (MIT)' "Copyright (c) Project Nayuki.`n`n$mit"

$dotnetRoot = Split-Path (Get-Command dotnet).Source
foreach ($file in @('LICENSE.txt', 'ThirdPartyNotices.txt')) {
    Add-Section ".NET host distribution: $file" (Get-Content (Join-Path $dotnetRoot $file) -Raw)
}
$normalized = [regex]::Replace($text.ToString().Replace("`r`n", "`n"), '(?m)[ \t]+$', '')
[System.IO.File]::WriteAllText($output, $normalized.TrimEnd() + "`n", [System.Text.UTF8Encoding]::new($false))
Write-Host "Generated $output ($($seen.Count) NuGet packages plus React, TypeScript and .NET notices)."
